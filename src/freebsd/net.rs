pub(crate) fn list_tcp_udp() -> Result<Vec<ConnectState>, LuminationError> {
    // First get connections using sysctl. Which is is a kernel call
    // Contains socket connections but no process name
    let mut conns = list_connections();

    // Now get process listing and additional connections. There is a small "race condition" when mapping connections to processes
    // If the process ends before we get the process listing we will not be able to get the process name
    // There is also a chance that the PID could be reused
    //list_procs(&mut conns)?;

    Ok(conns)
}

fn list_connections() -> Vec<ConnectState> {
    // Found using https://gitlab.com/alfix/nsysctl
    // nsysctl -dtFO net.inet.udp.pcblist
    //    4.2.17.5: net.inet.udp.pcblist: List of active UDP sockets: opaque: S,xinpcb:
    let mut tcp_oid = vec![4, 2, 6, 11];
    let mut udp_oid = vec![4, 2, 17, 5];
    let mut conns = Vec::new();
    #[allow(unsafe_code)]
    unsafe {
        let mut val_len = 0;
        let status = sysctl(
            tcp_oid.as_mut_ptr(),
            tcp_oid.len() as u32,
            std::ptr::null_mut(),
            &mut val_len,
            std::ptr::null_mut(),
            0,
        );

        if status != 0 {
            error!(
                "[lumination] Failed to get tcp socket data size. Wanted status 0, got {status}"
            );
            return conns;
        }
        let mut val: Vec<libc::c_uchar> = vec![0; val_len];
        let mut new_val_len = val_len;
        let status = sysctl(
            tcp_oid.as_mut_ptr(),
            tcp_oid.len() as u32,
            val.as_mut_ptr().cast::<libc::c_void>(),
            &mut new_val_len,
            std::ptr::null_mut(),
            0,
        );
        if status != 0 {
            error!("[lumination] Failed to get tcp socket data. Wanted status 0, got {status}");
            return conns;
        }

        let tcp_conns = match parse_socket_options(&val, &Protocol::Tcp) {
            Ok((_, results)) => results,
            Err(err) => {
                error!("[lumination] Failed to parse tcp socket data: {err:?}");
                return conns;
            }
        };
        conns = tcp_conns;

        let mut val_len = 0;
        let status = sysctl(
            udp_oid.as_mut_ptr(),
            udp_oid.len() as u32,
            std::ptr::null_mut(),
            &mut val_len,
            std::ptr::null_mut(),
            0,
        );

        if status != 0 {
            error!(
                "[lumination] Failed to get udp socket data size. Wanted status 0, got {status}"
            );
            return conns;
        }

        let mut val: Vec<libc::c_uchar> = vec![0; val_len];
        let mut new_val_len = val_len;
        let status = sysctl(
            udp_oid.as_mut_ptr(),
            udp_oid.len() as u32,
            val.as_mut_ptr().cast::<libc::c_void>(),
            &mut new_val_len,
            std::ptr::null_mut(),
            0,
        );

        if status != 0 {
            error!("[lumination] Failed to get udp socket data. Wanted status 0, got {status}");
            return conns;
        }

        let mut udp_conns = match parse_socket_options(&val, &Protocol::Udp) {
            Ok((_, results)) => results,
            Err(err) => {
                error!("[lumination] Failed to parse udp socket data: {err:?}");
                return conns;
            }
        };
        conns.append(&mut udp_conns);
    }
    conns
}

/// Parse the socket format
/// We just grab what we need and leave
/// This data is obtained from the kernel syscall `net.inet.tcp.pcblist_n` and `net.inet.udp.pcblist_n`
/// This is what netstat does
fn parse_socket_options<'a>(
    data: &'a [u8],
    protocol: &Protocol,
) -> nom::IResult<&'a [u8], Vec<ConnectState>> {
    // Here be dragons...
    // Format: http://fxr.watson.org/fxr/source/netinet/in_pcb.h#L216
    let mut conns = Vec::new();

    // We just going to parse what we need and thats it
    let header_size: u8 = 64;
    let (input, _header_data) = take(header_size)(data)?;
    let mut remaining = input;

    let min_size = 616;
    let expected_tcp_size = 744;
    let expected_udp_size = 400;
    while remaining.len() > min_size {
        let (_, connection_size) = le_u16(remaining)?;
        if connection_size != expected_tcp_size && connection_size != expected_udp_size {
            break;
        }
        // Connection Size includes itself
        let (input, connection_data) = take(connection_size)(remaining)?;
        remaining = input;

        // Grab the ports
        let ports_offset: u16 = if protocol == &Protocol::Tcp { 260 } else { 252 };
        let (port_data, _) = take(ports_offset)(connection_data)?;
        let (input, remote_port) = be_u16(port_data)?;
        let (_, local_port) = be_u16(input)?;

        // Grab the IPs
        let ips_offset: u16 = if protocol == &Protocol::Tcp { 276 } else { 268 };
        let (ips_data, _) = take(ips_offset)(connection_data)?;

        let padding: u8 = 12;

        let ip_version_offset: u8 = if protocol == &Protocol::Tcp { 116 } else { 108 };
        let (ip_version_data, _) = take(ip_version_offset)(connection_data)?;
        let (_, is_ipv4) = le_u8(ip_version_data)?;
        //let is_ipv4 = 1;
        // Remote IP first
        let (input, remote_address) = if is_ipv4 == 2 {
            let (input, remote_ip) = be_u32(ips_data)?;
            let ip = Ipv4Addr::from_bits(remote_ip).to_string();
            let (input, _padding) = take(padding)(input)?;

            (input, ip)
        } else {
            let ip6_padding: u8 = 4;
            let (input, _padding) = take(ip6_padding)(input)?;

            let (input, remote_ip) = be_u128(input)?;
            let ip = Ipv6Addr::from_bits(remote_ip).to_string();

            (input, ip)
        };

        // Now local IP
        let (_input, local_address) = if is_ipv4 == 2 {
            let (input, src_ip) = be_u32(input)?;
            let ip = Ipv4Addr::from_bits(src_ip).to_string();
            (input, ip)
        } else {
            let ip6_padding: u8 = 4;
            let (input, _padding) = take(ip6_padding)(input)?;

            let (input, src_ip) = be_u128(input)?;
            let ip = Ipv6Addr::from_bits(src_ip).to_string();
            (input, ip)
        };

        let mut conn = ConnectState {
            protocol: protocol.clone(),
            local_address,
            local_port,
            remote_address,
            remote_port,
            state: NetworkState::Unknown,
            pid: 0,
            process_name: String::new(),
        };

        if protocol == &Protocol::Tcp {
            parse_state(connection_data, &mut conn)?;
        }
        conns.push(conn);
    }

    Ok((&[], conns))
}

/// Parse connection state. Lots of info here. But we only care about the network state
fn parse_state<'a>(data: &'a [u8], conn: &mut ConnectState) -> nom::IResult<&'a [u8], ()> {
    let state_offset: u16 = 568;
    let (state_start, _) = take(state_offset)(data)?;
    let (_, state) = le_u8(state_start)?;
    conn.state = get_state(state);

    Ok((&[], ()))
}

/// Determine connection state
/// Sames as macOS
/// https://www.leidinger.net/FreeBSD/dox/netinet/html/de/d32/tcp__fsm_8h.html
pub(crate) fn get_state(state: u8) -> NetworkState {
    match state {
        0 => NetworkState::Close,
        1 => NetworkState::Listen,
        2 => NetworkState::SynSent,
        3 => NetworkState::SynRecv,
        4 => NetworkState::Established,
        5 => NetworkState::CloseWait,
        6 => NetworkState::FinWait,
        7 => NetworkState::Closing,
        8 => NetworkState::LastAck,
        9 => NetworkState::FinWait2,
        10 => NetworkState::TimeWait,
        _ => NetworkState::Unknown,
    }
}

